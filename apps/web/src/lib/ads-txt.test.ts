/**
 * The authorised-sellers file, asserted as the crawler reads it: the records
 * in the emitted text, each once, from both partners while the site applies to
 * both - and nothing for a source that names nobody.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  GOOGLE_TAG_ID,
  PUBLISHER_ID_PATTERN,
  buildAdsTxt,
  googleRecord,
  recordKey,
  sellerRecords,
} from './ads-txt.mjs';

const MARKER = '# Auto-generated by scripts/generate-ads-txt.mjs.';
const CLIENT = 'ca-pub-1962579532222274';
const GOOGLE = `google.com, pub-1962579532222274, DIRECT, ${GOOGLE_TAG_ID}`;

/** A stand-in for the file Journey issues: comments, variables, Mediavine's own Google seats. */
const JOURNEY = [
  '# Mediavine ads.txt for sleekdrops.com',
  'OWNERDOMAIN=sleekdrops.com',
  'MANAGERDOMAIN=mediavine.com',
  'google.com, pub-1234567890123456, RESELLER, f08c47fec0942fa0',
  'GOOGLE.COM, pub-1962579532222274, direct, F08C47FEC0942FA0 # the site owner\'s own seat',
  'rubiconproject.com, 12345, RESELLER, 0bfd66d529a55807',
  'rubiconproject.com, 12345, RESELLER, 0bfd66d529a55807',
].join('\n');

test('the AdSense record names the seller without the tag prefix', () => {
  assert.equal(googleRecord(CLIENT), GOOGLE);
  assert.ok(PUBLISHER_ID_PATTERN.test(CLIENT));
  assert.ok(!PUBLISHER_ID_PATTERN.test('pub-1962579532222274'));
  assert.ok(!PUBLISHER_ID_PATTERN.test(`${CLIENT}\ngoogle.com, pub-evil, DIRECT, ${GOOGLE_TAG_ID}`));
});

test('with only a publisher id the file is the one Google record', () => {
  const { text, count } = buildAdsTxt({ marker: MARKER, client: CLIENT });
  assert.equal(count, 1);
  assert.ok(text.startsWith(`${MARKER}\n`), 'the marker is what lets a later build remove the file');
  assert.deepEqual(sellerRecords(text), [GOOGLE]);
});

test("with Journey's file too, every record from both is published once", () => {
  const { text, count } = buildAdsTxt({
    marker: MARKER,
    client: CLIENT,
    journey: { contents: JOURNEY, origin: 'ads/ads.txt' },
  });
  const records = sellerRecords(text);
  assert.equal(records[0], GOOGLE, 'the AdSense record comes first');
  assert.equal(count, records.length);
  assert.equal(new Set(records.map(recordKey)).size, records.length, 'no record appears twice');
  assert.deepEqual(
    records.map(recordKey).sort(),
    [
      recordKey(GOOGLE),
      recordKey('google.com, pub-1234567890123456, RESELLER, f08c47fec0942fa0'),
      recordKey('rubiconproject.com, 12345, RESELLER, 0bfd66d529a55807'),
    ].sort(),
  );
  // Journey's variables and comments are its own and go out as issued.
  assert.match(text, /^OWNERDOMAIN=sleekdrops\.com$/m);
  assert.match(text, /^MANAGERDOMAIN=mediavine\.com$/m);
  assert.match(text, /^# Journey by Mediavine - from ads\/ads\.txt, as issued\.$/m);
});

test("Journey's file alone is published as issued", () => {
  const { text, count } = buildAdsTxt({ marker: MARKER, journey: { contents: JOURNEY, origin: 'ads/ads.txt' } });
  assert.doesNotMatch(text, /# Google AdSense/);
  // Its duplicate rubicon line collapses; its own two google.com seats both stay.
  assert.equal(count, 3);
});

test('a record key ignores case where ads.txt does and keeps account ids as written', () => {
  assert.equal(
    recordKey('GOOGLE.COM, pub-1, direct, F08C47FEC0942FA0 # note'),
    recordKey('google.com,pub-1,DIRECT,f08c47fec0942fa0'),
  );
  assert.notEqual(recordKey('example.com, AbC, DIRECT'), recordKey('example.com, abc, DIRECT'));
});

test('a 404 page or an HTML error carries no seller record', () => {
  assert.deepEqual(sellerRecords('<!doctype html><title>404 Not Found</title>'), []);
  assert.deepEqual(sellerRecords('# only a comment\nOWNERDOMAIN=sleekdrops.com\n'), []);
});

test('the prebuild runs the generator, and the generator uses this rule', () => {
  const pkg = JSON.parse(readFileSync(fileURLToPath(new URL('../../package.json', import.meta.url)), 'utf8'));
  assert.match(pkg.scripts.prebuild, /generate-ads-txt\.mjs/);
  const script = readFileSync(fileURLToPath(new URL('../../scripts/generate-ads-txt.mjs', import.meta.url)), 'utf8');
  assert.match(script, /from '\.\.\/src\/lib\/ads-txt\.mjs'/);
  assert.match(script, /startsWith\(MARKER\)/, 'a stale file is removed only when this script wrote it');
});
