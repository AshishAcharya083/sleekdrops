test('plainText keeps prose and drops everything a crawler should not read', () => {
  assert.equal(plainText('**Bold** and [a link](/go/slug) and `code`'), 'Bold and a link and code');
  assert.equal(plainText('![alt](https://img.example/x.png) after'), 'after');
  assert.equal(plainText('a <span class="x">tag</span> b'), 'a tag b');
  // A table's cells are prose; its pipes and alignment row are not words.
  assert.equal(
    plainText('| Model | RRP |\n| --- | --- |\n| Shark | $499 |'),
    'Model RRP Shark $499',
  );
});

test('a future update date cannot score above a page checked today', () => {
  // A scheduled re-publish would otherwise push the recency signal past 1 and
  // rank a post the site has not touched yet above everything else.
  const base = { title: 'A', dek: 'A', category: 'Tech', pubDate: '2026-09-01', tags: [] };
  const body = `## One\n\n${filler(1600)}`;
  const scheduled = toArticleRecord('a', { ...base, updatedDate: '2027-06-01' }, body, NOW);
  const today = toArticleRecord('b', { ...base, updatedDate: '2026-09-09' }, body, NOW);
  assert.equal(strengthSignals(scheduled, NOW).recency, 1);
  assert.equal(scoreArticle(scheduled, NOW), scoreArticle(today, NOW));
});
