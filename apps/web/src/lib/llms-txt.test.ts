/** A fixture written exactly as fetch-content.mjs writes a post. */
function writeFixture(dir: string, fixture: Fixture): void {
  const lines = ['---'];
  for (const [key, value] of Object.entries(fixture.frontmatter)) {
    if (value === undefined) continue;
    lines.push(`${key}: ${JSON.stringify(value)}`);
  }
  lines.push('---');
  writeFileSync(join(dir, `${fixture.slug}.md`), `${lines.join('\n')}\n\n${fixture.body.trim()}\n`, 'utf8');
}

const collection = mkdtempSync(join(tmpdir(), 'llms-txt-fixture-'));
