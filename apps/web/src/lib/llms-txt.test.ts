test('strength rewards evidence and figures over length alone', () => {
  const base = {
    title: 'A',
    dek: 'A',
    category: 'Tech',
    postType: 'guide',
    author: 'theo',
    pubDate: '2026-09-01',
    tags: [],
  };
  const record = (body: string, extra: Record<string, unknown> = {}) =>
    toArticleRecord('a', { ...base, ...extra }, body, NOW);

  const padded = record(`## One\n\n${filler(1600)}`);
  const evidenced = record(
    `## One\n\n${filler(1400)} The Shark holds 38 minutes of runtime at $499 RRP (Shark, 2026 price list), against 60 minutes at $1,099 (Dyson, 2026 RRP).`,
  );
  assert.ok(scoreArticle(evidenced, NOW) > scoreArticle(padded, NOW), 'dated, checkable claims must count for more');

  const stale = record(`## One\n\n${filler(1600)}`, { pubDate: '2024-01-01' });
  assert.ok(scoreArticle(padded, NOW) > scoreArticle(stale, NOW), 'freshness is a ranking signal for engines');

  const maintained = record(`## One\n\n${filler(1600)}`, { updatedDate: '2026-09-08' });
  assert.ok(scoreArticle(maintained, NOW) > scoreArticle(padded, NOW), 'a re-checked page is a stronger citation');
});

test('every weighted signal is one the scorer computes, and stays inside 0-1', () => {
  // A weight with no signal, or a signal with no weight, would turn every score
  // into NaN and leave the ranking in file order without failing anything.
  const strongest = articles[0];
  const signals = strengthSignals(strongest, NOW);
  assert.deepEqual(Object.keys(signals).sort(), Object.keys(STRENGTH_WEIGHTS).sort());
  for (const [signal, value] of Object.entries(signals)) {
    assert.ok(value >= 0 && value <= 1, `${signal} is ${value}, outside 0-1`);
  }
  assert.ok(Number.isFinite(strongest.score) && strongest.score > 0);
  const ceiling = Object.values(STRENGTH_WEIGHTS).reduce((sum, weight) => sum + weight, 0);
  assert.ok(strongest.score <= ceiling);
});

