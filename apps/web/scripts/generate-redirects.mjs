// Materializes the affiliate redirect layer from the affiliate-links.json
// produced by scripts/fetch-content.mjs (from the D1 affiliate_links table).
//
// Two outputs:
//   1. functions/_data/affiliate-links.mjs — the link table, imported by the
//      Pages Function functions/go/[slug].js. The Function picks the per-region,
//      per-network destination at request time (it can read cf.country; a static
//      _redirects file cannot). Functions own /go/* — they take precedence over
//      _redirects for matching routes.
//   2. public/_redirects — now only system-level rewrites (legacy URL → new).
//      Affiliate /go/<slug> rules are NO LONGER emitted here; the Function
//      handles them. Kept so future non-geo rewrites have a home.
//
// Run after fetch-content (see package.json -> scripts.prebuild). Safe to
// re-run; outputs are overwritten in place.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SOURCE = resolve(ROOT, '.d1-cache/affiliate-links.json');
const TARGET = resolve(ROOT, 'public/_redirects');
const DATA_TARGET = resolve(ROOT, 'functions/_data/affiliate-links.mjs');

function fail(message) {
  console.error(`\n[generate-redirects] ${message}\n`);
  process.exit(1);
}

if (!existsSync(SOURCE)) {
  fail(
    `Missing ${SOURCE}. Run \`node scripts/fetch-content.mjs\` first (or just \`pnpm prebuild\`).`,
  );
}

let parsed;
try {
  parsed = JSON.parse(readFileSync(SOURCE, 'utf8'));
} catch (err) {
  fail(`Invalid JSON in ${SOURCE}: ${err.message}`);
}

const links = parsed.links ?? {};
const entries = Object.entries(links);

const header = [
  '# Auto-generated by scripts/generate-redirects.mjs.',
  '# Source: .d1-cache/affiliate-links.json (from the D1 affiliate_links table).',
  '# Do NOT edit by hand — your changes will be overwritten on the next build.',
  `# Generated: ${new Date().toISOString()}`,
  '',
];

// Reserved for future system-level rewrites (e.g., legacy URL → new URL).
const systemRewrites = [];

// Validate every entry has a fallback destination. `default` is the safety net
// the Function falls back to when a network builder can't produce a URL (e.g.
// missing region ASIN or unset credentials), so it must always be present.
for (const [slug, entry] of entries) {
  if (!entry || typeof entry !== 'object') {
    fail(`Entry "${slug}" is not an object.`);
  }
  if (!entry.default || typeof entry.default !== 'string') {
    fail(`Entry "${slug}" is missing a "default" destination URL.`);
  }
}

// (1) Function data module: the whole link table, picked apart at request time
// by functions/go/[slug].js. Generated (gitignored) — regenerated every build.
const dataModule = [
  '// AUTO-GENERATED by scripts/generate-redirects.mjs — do NOT edit by hand.',
  '// Source: .d1-cache/affiliate-links.json (from the D1 affiliate_links table).',
  `// Generated: ${new Date().toISOString()}`,
  `export default ${JSON.stringify(links, null, 2)};`,
  '',
].join('\n');
mkdirSync(dirname(DATA_TARGET), { recursive: true });
writeFileSync(DATA_TARGET, dataModule, 'utf8');

// (2) _redirects: only system rewrites now. /go/* is owned by the Function.
const output = [
  ...header,
  '# Affiliate /go/<slug> redirects are handled by functions/go/[slug].js',
  '# (geo- and network-aware) — they are intentionally NOT emitted here.',
  '',
  ...systemRewrites,
  '',
].join('\n');

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, output, 'utf8');

console.log(
  `[generate-redirects] Wrote ${entries.length} link(s) → ${DATA_TARGET}`,
);
console.log(
  `[generate-redirects] Wrote ${systemRewrites.length} system rewrite(s) → ${TARGET}`,
);
