// Materializes public/ads.txt - the IAB authorized-sellers file the ad partners
// read from the site root to confirm who may sell this domain's inventory.
//
// The site is set up for two partners while it applies to both, and the file is
// the union of what each needs (the rule itself lives in src/lib/ads-txt.mjs):
//
// - Google AdSense: one record, generated from the production publisher id
//   (PUBLIC_ADSENSE_CLIENT, the same value src/lib/ads-env.ts loads the
//   publisher tag with).
// - Journey by Mediavine: the file Journey issues in its dashboard (Settings >
//   Ad Setup) once it approves the site - a copy committed at ads/ads.txt, or,
//   for a partner that hosts the file itself, the URL in ADS_TXT_URL, fetched at
//   build time. Neither exists until Journey issues one. See ads/README.md.
//
// It is written into public/ - Astro copies that directory to the site root
// verbatim, which is the only place a crawler looks for /ads.txt - alongside
// the generated _redirects, and is gitignored for the same reason that one is.
//
// Production only. Outside production the file is not written at all, and any
// file a previous build left behind is removed: sleekdrops.pages.dev is not a
// domain either partner approved, and an ads.txt there authorises sellers for a
// site that does not exist. With no source configured the same happens, and an
// ads.txt authorizing nobody is worse than none, because that is the file a
// crawler reads as "this domain has revoked every seller".
//
// Every source is validated before anything is published, and a source that
// fails fails the build: the publisher id must read ca-pub-<digits>, and
// Journey's file must carry at least one `domain, seller id, DIRECT|RESELLER`
// record - a 404 page or an HTML error saved under the name would publish a
// file naming nobody, and the partner's health check would flag the site while
// the deploy read as green.
//
// Run before the build (see package.json -> scripts.prebuild). Safe to re-run;
// the output is overwritten in place.

import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PUBLISHER_ID_PATTERN, buildAdsTxt, sellerRecords } from '../src/lib/ads-txt.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(__dirname, '../ads/ads.txt');
const TARGET = resolve(__dirname, '../public/ads.txt');

const MARKER = '# Auto-generated by scripts/generate-ads-txt.mjs.';

function fail(message) {
  console.error(`\n[generate-ads-txt] ${message}\n`);
  process.exit(1);
}

/** Only ever removes a file this script wrote - never a hand-placed one. */
function removeGenerated(reason) {
  if (!existsSync(TARGET)) {
    console.log(`[generate-ads-txt] ${reason} - no ads.txt is published.`);
    return;
  }
  if (!readFileSync(TARGET, 'utf8').startsWith(MARKER)) {
    console.warn('[generate-ads-txt] public/ads.txt was not generated by this script - leaving it alone.');
    return;
  }
  rmSync(TARGET);
  console.log(`[generate-ads-txt] ${reason} - removed the generated public/ads.txt.`);
}

/** Journey's issued file - ADS_TXT_URL first, then the committed copy - or null until there is one. */
async function journeySource(url) {
  if (!url) {
    return existsSync(SOURCE) ? { contents: readFileSync(SOURCE, 'utf8'), origin: 'ads/ads.txt' } : null;
  }
  let response;
  try {
    response = await fetch(url, { signal: AbortSignal.timeout(15_000) });
  } catch (error) {
    fail(`could not fetch ADS_TXT_URL (${url}): ${error.message}`);
  }
  if (!response.ok) fail(`ADS_TXT_URL (${url}) answered HTTP ${response.status}.`);
  return { contents: await response.text(), origin: `ADS_TXT_URL (${url})` };
}

const production = (process.env.PUBLIC_SITE_ENV ?? '').trim() === 'production';
const client = (process.env.PUBLIC_ADSENSE_CLIENT ?? '').trim();
const url = (process.env.ADS_TXT_URL ?? '').trim();

if (!production) {
  removeGenerated('non-production build');
} else {
  if (client && !PUBLISHER_ID_PATTERN.test(client)) {
    fail('PUBLIC_ADSENSE_CLIENT is not a publisher id (expected ca-pub-<digits>) - refusing to write public/ads.txt.');
  }
  const journey = await journeySource(url);
  if (journey && sellerRecords(journey.contents).length === 0) {
    fail(
      `${journey.origin} carries no authorised-seller record (expected at least one ` +
        '`domain, seller id, DIRECT|RESELLER` line) - refusing to publish public/ads.txt.',
    );
  }

  if (!client && !journey) {
    removeGenerated('no PUBLIC_ADSENSE_CLIENT, no ADS_TXT_URL and no ads/ads.txt');
  } else {
    const { text, count } = buildAdsTxt({ marker: MARKER, client, journey });
    writeFileSync(TARGET, text, 'utf8');
    const origins = [client && 'PUBLIC_ADSENSE_CLIENT', journey?.origin].filter(Boolean).join(' + ');
    console.log(`[generate-ads-txt] wrote public/ads.txt (${count} seller record(s)) from ${origins}.`);
  }
}
