// Materializes public/llms.txt and public/llms-full.txt - the curated map of
// what this site knows, written for a retrieval agent rather than a reader.
//
// The site had neither, so an AI crawler arriving here got the sitemap and
// nothing else: no statement of what the site covers, no ranking of what it
// covers WELL, and no machine-readable route to an article's substance. The
// rules that decide all three live in src/lib/llms-txt.mjs, where they are
// unit-tested; this script is the wiring - read the content collection, load the
// site's own name, description and categories, write the two files.
//
// Generated rather than committed for the reason _redirects, ads.txt and
// robots.txt are: the content changes on every publish and the URLs are built
// from SITE_URL, so a committed file would be stale the moment an article ships
// and would name the wrong host on a preview build. Written into public/ - Astro
// copies that directory to the site root verbatim, which is the only place an
// agent looks for /llms.txt - and gitignored for the same reason.
//
// With no live articles - a fresh checkout, or a collection of nothing but
// drafts - the files are not written at all, and any file a previous build left
// behind is removed. An llms.txt that maps no content is worse than none: it is
// a published claim that this site knows nothing. generate-robots.mjs runs after
// this one and only advertises the files when they exist, so robots.txt can
// never point an agent at a 404.
//
// Requires Node's type stripping (--experimental-strip-types, as
// scripts/check-anchors.mjs does) because the site description and the category
// registry are the TypeScript modules the pages themselves read: one source of
// truth, not a second copy that drifts.
//
// Run before the build (see package.json -> scripts.prebuild). Safe to re-run;
// the output is overwritten in place.

import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { categories } from '../src/data/categories.ts';
import { SITE_DESCRIPTION, SITE_NAME } from '../src/data/site.ts';
import { buildLlmsFullTxt, buildLlmsTxt, readArticleIndex } from '../src/lib/llms-txt.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const BLOG_DIR = resolve(ROOT, 'src/content/blog');

const TARGETS = {
  curated: resolve(ROOT, 'public/llms.txt'),
  full: resolve(ROOT, 'public/llms-full.txt'),
};

/** Both files carry this, which is how the removal below knows they are ours. */
const MARKER = 'Generated by scripts/generate-llms-txt.mjs';

/** The only value that means "this is the real site" - see src/lib/site-env.ts. */
const PRODUCTION = 'production';

/** Only ever removes a file this script wrote - never a hand-placed one. */
function removeGenerated(path, label) {
  if (!existsSync(path)) return;
  if (!readFileSync(path, 'utf8').includes(MARKER)) {
    console.warn(`[generate-llms-txt] public/${label} was not generated by this script - leaving it alone.`);
    return;
  }
  rmSync(path);
  console.log(`[generate-llms-txt] no live articles - removed the generated public/${label}.`);
}

const deployment = (process.env.PUBLIC_SITE_ENV ?? '').trim() === PRODUCTION ? PRODUCTION : 'preview';
const siteUrl = (process.env.SITE_URL ?? 'https://sleekdrops.com').trim().replace(/\/+$/, '');

const articles = readArticleIndex(BLOG_DIR);

if (articles.length === 0) {
  removeGenerated(TARGETS.curated, 'llms.txt');
  removeGenerated(TARGETS.full, 'llms-full.txt');
} else {
  const input = {
    siteName: SITE_NAME,
    siteUrl,
    description: SITE_DESCRIPTION,
    categories,
    articles,
    deployment,
    generatedAt: new Date(),
    marker: MARKER,
  };
  writeFileSync(TARGETS.curated, buildLlmsTxt(input), 'utf8');
  writeFileSync(TARGETS.full, buildLlmsFullTxt(input), 'utf8');
  console.log(
    `[generate-llms-txt] wrote public/llms.txt and public/llms-full.txt from ${articles.length} live article(s) ` +
      `for ${deployment} (${siteUrl}).`,
  );
}
