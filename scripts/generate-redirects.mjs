// Generates public/_redirects from src/data/affiliate-links.json.
//
// Cloudflare Pages reads public/_redirects natively and serves the rules at the
// edge — no Worker, no runtime cost, no extra request. Every /go/[slug] becomes
// a 302 to the destination URL in the JSON.
//
// Run automatically before `astro build` (see package.json -> scripts.build).
// Safe to re-run; the file is overwritten in place.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SOURCE = resolve(ROOT, 'src/data/affiliate-links.json');
const TARGET = resolve(ROOT, 'public/_redirects');

function fail(message) {
  console.error(`\n[generate-redirects] ${message}\n`);
  process.exit(1);
}

if (!existsSync(SOURCE)) {
  fail(`Missing ${SOURCE}. Create it with { "links": {} } at minimum.`);
}

let parsed;
try {
  parsed = JSON.parse(readFileSync(SOURCE, 'utf8'));
} catch (err) {
  fail(`Invalid JSON in ${SOURCE}: ${err.message}`);
}

const links = parsed.links ?? {};
const entries = Object.entries(links);

const header = [
  '# Auto-generated by scripts/generate-redirects.mjs.',
  '# Source: src/data/affiliate-links.json (affiliate redirects) +',
  '# hard-coded rewrites in this script (sitemap, etc.).',
  '# Do NOT edit by hand — your changes will be overwritten on the next build.',
  `# Generated: ${new Date().toISOString()}`,
  '',
];

// Reserved for future system-level rewrites (e.g., legacy URL → new URL).
const systemRewrites = [];

const rules = [];
for (const [slug, entry] of entries) {
  if (!entry || typeof entry !== 'object') {
    fail(`Entry "${slug}" is not an object.`);
  }
  const destination = entry.default;
  if (!destination || typeof destination !== 'string') {
    fail(`Entry "${slug}" is missing a "default" destination URL.`);
  }
  // 302 (temporary) so search engines don't index the redirect target. The
  // surrounding <a rel="sponsored nofollow"> tells crawlers not to follow.
  rules.push(`/go/${slug}\t${destination}\t302`);
}

const output = [
  ...header,
  ...systemRewrites,
  '# Affiliate redirects (one per /go/[slug]).',
  ...rules,
  '',
].join('\n');

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, output, 'utf8');

console.log(`[generate-redirects] Wrote ${rules.length} redirect rule(s) to ${TARGET}`);
